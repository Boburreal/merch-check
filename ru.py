def tr(s: str) -> str:
    if not isinstance(s, str) or not s or s.startswith('http') or s.startswith('='):
        return s
    for rx, rep in COMPILED:
        s = rx.sub(rep, s)
    return s


def translate_workbook(path: str):
    wb = load_workbook(path)
    for ws in wb.worksheets:
        for row in ws.iter_rows():
            for c in row:
                if isinstance(c.value, str):
                    v = tr(c.value)
                    if v != c.value:
                        c.value = v
        if ws.title in SHEETS:
            ws.title = SHEETS[ws.title][:31]
    wb.save(path)
